import { NextResponse, type NextRequest } from 'next/server';

const ADMIN_ROUTE_PERMISSIONS: Record<string, string> = {
  '/admin/payments': 'manage_payments',
  '/admin/exams': 'manage_exams',
  '/admin/courses': 'manage_courses',
  '/admin/students': 'manage_students',
  '/admin/forum': 'manage_forum',
  '/admin/settings': 'manage_settings',
};

function b64UrlToBytes(b64Url: string): Uint8Array {
  const pad = '='.repeat((4 - (b64Url.length % 4)) % 4);
  const raw = atob((b64Url + pad).replace(/-/g, '+').replace(/_/g, '/'));
  const bytes = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i++) {
    bytes[i] = raw.charCodeAt(i);
  }
  return bytes;
}

/**
 * Reassembles chunked auth cookies generated by @supabase/ssr
 */
function extractSupabaseJwt(request: NextRequest): string | null {
  // 1. Direct single cookie
  const directToken = request.cookies.get('sb-access-token')?.value;
  if (directToken) return directToken;

  // 2. Scan for Supabase SSR auth cookies (e.g., sb-xyz-auth-token or sb-xyz-auth-token.0, .1)
  const allCookies = request.cookies.getAll();
  const chunkedMap: Record<string, { base: string; index: number; value: string }[]> = {};

  for (const cookie of allCookies) {
    if (cookie.name.includes('-auth-token')) {
      const match = cookie.name.match(/^(sb-.*-auth-token)(?:\.(\d+))?$/);
      if (match) {
        const baseName = match[1];
        const index = match[2] ? parseInt(match[2], 10) : 0;
        if (!chunkedMap[baseName]) chunkedMap[baseName] = [];
        chunkedMap[baseName].push({ base: baseName, index, value: cookie.value });
      }
    }
  }

  for (const baseName in chunkedMap) {
    const sorted = chunkedMap[baseName].sort((a, b) => a.index - b.index);
    const combined = sorted.map((c) => c.value).join('');
    try {
      if (combined.startsWith('base64-')) {
        const rawBase64 = combined.replace('base64-', '');
        const decoded = new TextDecoder().decode(b64UrlToBytes(rawBase64));
        const parsed = JSON.parse(decoded);
        return parsed.access_token || (Array.isArray(parsed) ? parsed[0] : null);
      }
      const parsed = JSON.parse(combined);
      return parsed.access_token || (Array.isArray(parsed) ? parsed[0] : null);
    } catch {
      if (combined.split('.').length === 3) {
        return combined;
      }
    }
  }

  return null;
}

/**
 * Validates JWT locally on Cloudflare Edge via Web Crypto API (SubtleCrypto)
 */
async function verifyJwtOnEdge(token: string, secret?: string): Promise<Record<string, any> | null> {
  try {
    const parts = token.split('.');
    if (parts.length !== 3) return null;
    const [headerB64, payloadB64, signatureB64] = parts;

    // Verify signature if secret is provided in environment
    if (secret) {
      const enc = new TextEncoder();
      const key = await crypto.subtle.importKey(
        'raw',
        enc.encode(secret),
        { name: 'HMAC', hash: 'SHA-256' },
        false,
        ['verify']
      );
      const isValid = await crypto.subtle.verify(
        'HMAC',
        key,
        b64UrlToBytes(signatureB64) as unknown as BufferSource,
        enc.encode(`${headerB64}.${payloadB64}`)
      );
      if (!isValid) return null;
    }

    const payload = JSON.parse(new TextDecoder().decode(b64UrlToBytes(payloadB64)));
    if (payload.exp && payload.exp * 1000 <= Date.now()) {
      return null; // Expired
    }
    return payload;
  } catch {
    return null;
  }
}

export async function middleware(request: NextRequest) {
  const { pathname } = request.nextUrl;

  // Allow admin login page to be accessed publicly without token
  if (pathname === '/admin/login') {
    return NextResponse.next();
  }

  // Only guard /admin routes
  if (!pathname.startsWith('/admin')) {
    return NextResponse.next();
  }

  const token = extractSupabaseJwt(request);
  const secret = process.env.SUPABASE_JWT_SECRET;

  if (!token) {
    const loginUrl = new URL('/admin/login', request.url);
    loginUrl.searchParams.set('redirect', pathname);
    return NextResponse.redirect(loginUrl);
  }

  const payload = await verifyJwtOnEdge(token, secret);
  if (!payload) {
    const loginUrl = new URL('/admin/login', request.url);
    loginUrl.searchParams.set('redirect', pathname);
    return NextResponse.redirect(loginUrl);
  }

  const role = payload.app_metadata?.role || payload.user_metadata?.role;
  const permissions = payload.app_metadata?.permissions || {};

  // Super admins and admins have full access to everything in admin panel
  if (role === 'super_admin' || role === 'admin') {
    return NextResponse.next();
  }

  // Assistant RBAC permissions checking
  if (role === 'assistant') {
    for (const [prefix, permKey] of Object.entries(ADMIN_ROUTE_PERMISSIONS)) {
      if (pathname.startsWith(prefix) && permissions[permKey] !== true) {
        return NextResponse.redirect(new URL('/admin/unauthorized', request.url));
      }
    }
    return NextResponse.next();
  }

  // If user has a student or non-staff session, redirect them to admin login so they can log in with staff credentials
  const adminLoginUrl = new URL('/admin/login', request.url);
  adminLoginUrl.searchParams.set('redirect', pathname);
  return NextResponse.redirect(adminLoginUrl);
}

